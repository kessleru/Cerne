export function langOf(path: string): LangInfo {
  const name = path.slice(path.lastIndexOf('/') + 1);
  if (BY_NAME[name]) return BY_NAME[name]!;
  if (/^\.env(\.|$)/.test(name)) return BY_NAME['.env']!;
  if (/^Dockerfile\./i.test(name)) return BY_NAME.Dockerfile!;
  const lower = name.toLowerCase();
  const two = lower.split('.').slice(-2).join('.');
  if (BY_EXT[two] && lower.split('.').length > 2) return BY_EXT[two]!;
  const dot = name.lastIndexOf('.');
  const ext = dot > 0 ? lower.slice(dot + 1) : dot === 0 ? lower.slice(1) : '';
  return BY_EXT[ext] ?? { shiki: null, label: 'Texto' };
}

export function formatSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(bytes < 10240 ? 1 : 0).replace('.', ',')} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1).replace('.', ',')} MB`;
}

export function baseName(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}
